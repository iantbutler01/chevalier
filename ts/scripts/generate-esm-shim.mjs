// Generates index.mjs from the built CommonJS entry point.
//
// The implementation and the native addon loader are CommonJS, and this package
// is consumed from ESM projects. Rather than rely on Node's named-export
// auto-detection for CJS (which does not see everything this module re-exports),
// we emit an explicit shim.
//
// This used to be a hand-maintained file, which meant a symbol added to
// index.ts was invisible to ESM consumers until someone remembered to add it
// here -- and the failure surfaced only at load time as
// "does not provide an export named ...", so neither tsc nor the test suite
// caught it. Generating it from the real export list removes that drift.
import { createRequire } from "node:module";
import { writeFileSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const pkgRoot = join(here, "..");
const require = createRequire(join(pkgRoot, "package.json"));

const cjs = require("./index.js");
const names = Object.keys(cjs)
  .filter((name) => name !== "default" && /^[A-Za-z_$][\w$]*$/.test(name))
  .sort((a, b) => a.localeCompare(b));

if (names.length === 0) {
  throw new Error("generate-esm-shim: index.js exported nothing; refusing to write an empty shim");
}

const out = `// GENERATED by scripts/generate-esm-shim.mjs -- do not edit.
//
// ESM entry point. The implementation (and the native addon loader) is
// CommonJS; this re-exports it so \`import { Runtime } from "chevalier"\` works
// in ESM / "type": "module" projects without relying on named-export
// auto-detection. Regenerated on every build from index.js's actual exports.
import cjs from "./index.js";

export const {
${names.map((name) => `  ${name},`).join("\n")}
} = cjs;
export default cjs;
`;

const target = join(pkgRoot, "index.mjs");
const previous = (() => {
  try {
    return readFileSync(target, "utf8");
  } catch {
    return null;
  }
})();
if (previous !== out) {
  writeFileSync(target, out);
  console.log(`generate-esm-shim: wrote ${names.length} export(s)`);
} else {
  console.log(`generate-esm-shim: up to date (${names.length} exports)`);
}
